/**
 * Starter translations for a language code or locale (e.g. "de" or "de_DE").
 *
 * @param string $code Language code or locale.
 * @return array Text key => text, or empty array if none is bundled.
 */
function gdprcn_starter_translation( $code ) {
	$all  = gdprcn_starter_translations();
	$code = strtolower( (string) $code );
	$base = strtok( str_replace( '-', '_', $code ), '_' );

	return isset( $all[ $code ] ) ? $all[ $code ] : ( isset( $all[ $base ] ) ? $all[ $base ] : array() );
}

